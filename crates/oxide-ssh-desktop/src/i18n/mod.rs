#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ResolvedLocale {
    EnUs,
    ZhCn,
}

impl ResolvedLocale {
    pub fn resolve(setting: LocaleSetting, system_locale: Option<&str>) -> Self {
        match setting {
            LocaleSetting::EnUs => Self::EnUs,
            LocaleSetting::ZhCn => Self::ZhCn,
            LocaleSetting::System => {
                let locale = system_locale
                    .unwrap_or_default()
                    .replace('_', "-")
                    .to_ascii_lowercase();
                if locale == "zh" || locale.starts_with("zh-") {
                    Self::ZhCn
                } else {
                    Self::EnUs
                }
            }
        }
    }
}

pub struct Catalog;

impl Catalog {
    pub fn text(locale: ResolvedLocale, id: MessageId) -> &'static str {
        match locale {
            ResolvedLocale::EnUs => en::text(id),
            ResolvedLocale::ZhCn => zh_cn::text(id),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_message_id_has_english_and_chinese_text() {
        for id in MessageId::ALL {
            assert!(!Catalog::text(ResolvedLocale::EnUs, *id).is_empty());
            assert!(!Catalog::text(ResolvedLocale::ZhCn, *id).is_empty());
        }
    }

    #[test]
    fn field_examples_are_short_and_localized() {
        for locale in [ResolvedLocale::EnUs, ResolvedLocale::ZhCn] {
            assert_eq!(
                Catalog::text(locale, MessageId::KeepaliveIntervalExample),
                "30"
            );
            assert_eq!(
                Catalog::text(locale, MessageId::KeepaliveMaxCountExample),
                "3"
            );
            assert_eq!(
                Catalog::text(locale, MessageId::TerminalFontSizeExample),
                "14"
            );
            assert_eq!(
                Catalog::text(locale, MessageId::TerminalLineHeightExample),
                "20"
            );
            assert_eq!(
                Catalog::text(locale, MessageId::TerminalColorExample),
                "#1E1E1E"
            );
            assert_eq!(
                Catalog::text(locale, MessageId::EnvironmentVariablesExample),
                r#"[{"name":"LANG","value":"C"}]"#
            );
        }
    }

    #[test]
    fn system_locale_uses_chinese_only_for_zh_locales() {
        assert_eq!(
            ResolvedLocale::resolve(LocaleSetting::System, Some("zh-Hans-CN")),
            ResolvedLocale::ZhCn
        );
        assert_eq!(
            ResolvedLocale::resolve(LocaleSetting::System, Some("en-US")),
            ResolvedLocale::EnUs
        );
        assert_eq!(
            ResolvedLocale::resolve(LocaleSetting::System, None),
            ResolvedLocale::EnUs
        );
    }
}
